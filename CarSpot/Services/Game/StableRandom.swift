import Foundation

/// Generatore deterministico: FNV-1a 64 bit della stringa (utf8) come seme, poi SplitMix64.
/// Stesso seme = stessa sequenza su ogni telefono e a ogni avvio (mai `hashValue`).
struct StableRandom: RandomNumberGenerator, Sendable {
    private var state: UInt64

    init(seed: String) {
        var hash: UInt64 = 0xcbf29ce484222325
        for byte in seed.utf8 {
            hash ^= UInt64(byte)
            hash = hash &* 0x100000001b3
        }
        state = hash
    }

    mutating func next() -> UInt64 {
        state &+= 0x9E3779B97F4A7C15
        var z = state
        z = (z ^ (z >> 30)) &* 0xBF58476D1CE4E5B9
        z = (z ^ (z >> 27)) &* 0x94D049BB133111EB
        return z ^ (z >> 31)
    }
}
